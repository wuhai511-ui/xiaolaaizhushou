const assert = require('node:assert/strict');
const {resolveSchema, choicesFor, safeHistoryResult, imageFromClipboard, businessDefaults, canCheckPayment} = require('./xiaola-schema.js');
assert.deepEqual(choicesFor({anyOf:[{type:'number',const:1},{type:'number',const:2}]}),[1,2]);
assert.equal(resolveSchema({anyOf:[{type:'object',properties:{items:{type:'array'}}},{type:'string'}]}).type,'object');
assert.equal(resolveSchema({anyOf:[{type:'string',pattern:'^x$'},{type:'string',const:'0'}]}).type,'string');
const data=safeHistoryResult({status:'OK',result:{order_status:1006,order_no:'private',amount:1},email:'private@example.com'});
assert.deepEqual(data,{status:'OK',result:{order_status:1006,amount:1}});
const image={type:'image/png'};
assert.equal(imageFromClipboard([{kind:'string',type:'text/plain'},{kind:'file',type:'image/png',getAsFile:()=>image}]),image);
assert.equal(imageFromClipboard([{kind:'file',type:'application/pdf',getAsFile:()=>({})}]),null);
const ctx={jiaofeiyi:{merchantNo:'PAY',terminalNo:'TERM'},dianpiaotong:{merchantNo:'INVOICE',channel:'KINGDEE'}};
assert.deepEqual(businessDefaults('jiaofeiyiOrderQuery',ctx),{merchant_no:'PAY',term_no:'TERM'});
assert.deepEqual(businessDefaults('lqInvoiceCreate',ctx),{merchant_no:'INVOICE',channel:'KINGDEE'});
assert.deepEqual(businessDefaults('qztOrderStatusQuery',ctx),{});
assert.deepEqual(businessDefaults('lqInvoiceCreate',{jiaofeiyi:ctx.jiaofeiyi}),{});
assert.equal(canCheckPayment({order:'A',amount:'1.20',merchant:'M',terminal:'T'},false),true);
assert.equal(canCheckPayment({order:'A',amount:'1.20',merchant:'M',terminal:'T'},true),false);
assert.equal(canCheckPayment({order:'A',amount:'1.20',merchant:'M',terminal:''},false),false);
console.log('schema choices, nested forms, and history privacy checks passed');
